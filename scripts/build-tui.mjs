#!/usr/bin/env node
// Compile the terminal panel's JSX (src/tui-view.jsx) to the JavaScript OpenCode loads (src/tui.js).
//
// OpenCode compiles a plugin's JSX when it loads it, but OpenCode 2.3.0 (OpenTUI 0.8.4) skips every
// file under node_modules, which is where it installs npm and Git packages; anomalyco/opentui#2051
// compiles them again from OpenTUI 0.9.0 on. So the compiled file is part of the repository and of
// the package, made with the settings OpenTUI itself uses for plugin JSX: Solid's universal renderer,
// imported from @opentui/solid. Nothing is built when the plugin is installed.
//
//   node scripts/build-tui.mjs           write src/tui.js
//   node scripts/build-tui.mjs --check   fail when src/tui.js is not what the source compiles to
//
// The compiler is a development dependency (npm ci); the package itself has no dependency.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const SOURCE = new URL('../src/tui-view.jsx', import.meta.url);
const OUTPUT = new URL('../src/tui.js', import.meta.url);

/** The compiled module for `source`, with the header that names its origin. */
export async function compileTui(source) {
  let babel, solid, versions;
  try {
    const require = createRequire(import.meta.url);
    ({ default: babel } = await import('@babel/core'));
    ({ default: solid } = await import('babel-preset-solid'));
    versions = `@babel/core ${require('@babel/core/package.json').version}, babel-preset-solid ${require('babel-preset-solid/package.json').version}`;
  } catch (error) {
    throw new Error(`The JSX compiler is not installed (${error.code ?? error.message}). Run "npm ci" in the repository first.`);
  }
  const result = await babel.transformAsync(source, {
    filename: fileURLToPath(SOURCE), configFile: false, babelrc: false, sourceType: 'module', compact: false, comments: true,
    presets: [[solid, { moduleName: '@opentui/solid', generate: 'universal' }]],
  });
  return `// Generated from tui-view.jsx by scripts/build-tui.mjs (${versions}; Solid universal renderer from @opentui/solid).\n` +
    '// Do not edit this file: change tui-view.jsx and run "npm run build:tui". "npm run check" fails when the two differ.\n' +
    `${result.code}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv[2] === '--check';
  if (process.argv.length > (check ? 3 : 2)) { console.error('Usage: node scripts/build-tui.mjs [--check]'); process.exit(2); }
  try {
    const compiled = await compileTui(await readFile(SOURCE, 'utf8'));
    if (!check) {
      await writeFile(OUTPUT, compiled);
      console.log(`src/tui.js written (${compiled.length} characters).`);
    } else if (await readFile(OUTPUT, 'utf8').catch(() => '') !== compiled) {
      console.error('src/tui.js is not what src/tui-view.jsx compiles to. Run "npm run build:tui" and commit both files.');
      process.exit(1);
    } else console.log('src/tui.js matches src/tui-view.jsx.');
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
